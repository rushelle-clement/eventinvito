// The invitation templates. `tier`: "premium" = animated designs, "free" = simple static cards.
// `npm run seed:templates` writes these to MongoDB. Running it again updates them.
// A Signature custom design gets `custom: true`: it stays hidden until the admin gives it to the
// couple on the admin page, and joins the collection after their event (see utils/customDesigns.js).

const COMMON_FIELDS = [
    "partnerOne",
    "partnerTwo",
    "hostLine",
    "partnerOneParents",
    "partnerTwoParents",
    "inviteLine",
    "message",
    "eventDate",
    "eventTime",
    "endTime",
    "venueName",
    "address",
    "mapUrl",
    "dressCode",
    "rsvpDeadline",
];

// Free static cards: no photos, music or RSVP
const STATIC_FIELDS = COMMON_FIELDS.filter((f) => f !== "rsvpDeadline");

// Birthdays: one person (celebrant) and their age, instead of a couple
const BIRTHDAY_FIELDS = ["celebrant", "age", ...COMMON_FIELDS.filter((f) => !["partnerOne", "partnerTwo", "partnerOneParents", "partnerTwoParents"].includes(f))];
const BIRTHDAY_STATIC_FIELDS = BIRTHDAY_FIELDS.filter((f) => f !== "rsvpDeadline");

// Corporate events: a company, the event's title and logo (and for an anniversary, the years)
const CORPORATE_FIELDS = ["companyName", "eventTitle", "milestone", "hostLine", "inviteLine", "message", "eventDate", "eventTime", "endTime", "venueName", "address", "mapUrl", "dressCode", "rsvpDeadline"];
const CORPORATE_STATIC_FIELDS = CORPORATE_FIELDS.filter((f) => f !== "rsvpDeadline");
const corporate = (tier, key, name, description, styleTags, palette, sortOrder) => ({
    key,
    name,
    description,
    eventType: "corporate",
    styleTags,
    palette,
    supportedFields: tier === "free" ? CORPORATE_STATIC_FIELDS : CORPORATE_FIELDS,
    tier,
    status: "published",
    version: 1,
    sortOrder,
});

// Christmas parties: the party's title and its hosts (companyName holds the hosts)
const CHRISTMAS_FIELDS = ["companyName", "eventTitle", "hostLine", "inviteLine", "message", "eventDate", "eventTime", "endTime", "venueName", "address", "mapUrl", "dressCode", "rsvpDeadline"];
const christmas = (tier, key, name, description, styleTags, palette, sortOrder) => ({
    key,
    name,
    description,
    eventType: "christmas",
    styleTags,
    palette,
    supportedFields: tier === "free" ? CHRISTMAS_FIELDS.filter((f) => f !== "rsvpDeadline") : CHRISTMAS_FIELDS,
    tier,
    status: "published",
    version: 1,
    sortOrder,
});

const birthdayPremium = (key, name, description, styleTags, palette, sortOrder) => ({
    key,
    name,
    description,
    eventType: "birthday",
    styleTags,
    palette,
    supportedFields: BIRTHDAY_FIELDS,
    tier: "premium",
    status: "published",
    version: 1,
    sortOrder,
});

const birthdayCard = (key, name, description, styleTags, palette, sortOrder) => ({
    key,
    name,
    description,
    eventType: "birthday",
    styleTags,
    palette,
    supportedFields: BIRTHDAY_STATIC_FIELDS,
    tier: "free",
    status: "published",
    version: 1,
    sortOrder,
});

